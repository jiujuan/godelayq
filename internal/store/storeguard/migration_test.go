package storeguard

// 迁移纪律守卫的自证（G7/Q11 卡 §5"人为违规必红"）：构造坏输入直接断言问题
// 清单非空——永久留作回归，不必临时改生产清单再还原。零误报是验收底线，
// 每条规则的"既有形态必须通过"用例与违规用例成对出现。

import (
	"path/filepath"
	"testing"

	"github.com/jiujuan/godelayq/internal/store/engine"
	"github.com/stretchr/testify/require"
)

func TestCheckMigrationVersions(t *testing.T) {
	require.Empty(t, CheckMigrationVersions([]engine.Migration{
		{Version: 1}, {Version: 2}, {Version: 3},
	}), "递增无重复的既有形态必须零误报")

	require.NotEmpty(t, CheckMigrationVersions([]engine.Migration{
		{Version: 1}, {Version: 2}, {Version: 2},
	}), "重复版本必红（两份 DDL 抢同一版本位）")

	require.NotEmpty(t, CheckMigrationVersions([]engine.Migration{
		{Version: 2}, {Version: 1},
	}), "乱序必红（Migrate 按清单序执行，乱序等于跳版）")

	require.NotEmpty(t, CheckMigrationVersions([]engine.Migration{
		{Version: 0},
	}), "非正版本必红")
}

func TestCheckMigrationPortable(t *testing.T) {
	require.Empty(t, CheckMigrationPortable([]engine.Migration{
		{Version: 1, UpPostgres: []string{`CREATE TABLE t (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)`}},
	}), "IDENTITY 形态零误报")

	require.Empty(t, CheckMigrationPortable([]engine.Migration{
		{Version: 1, Up: []string{`CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT)`}},
	}), "Up 是两方言共用的通用语句集，不在本规则范围（PG 上炸是响亮故障，不是静默事故）")

	require.NotEmpty(t, CheckMigrationPortable([]engine.Migration{
		{Version: 2, UpPostgres: []string{`CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT)`}},
	}), "UpPostgres 里裸 AUTOINCREMENT 必红（Q04 的事故形状）")

	require.Empty(t, CheckMigrationPortable(nil), "空清单零误报")
}

func TestCheckMigrationV1Frozen_GoldenRoundTrip(t *testing.T) {
	ms := []engine.Migration{
		{Version: 1, Up: []string{"CREATE TABLE a(x)", "CREATE INDEX i ON a(x)"}},
	}
	golden := filepath.Join(t.TempDir(), "migration_v1.golden")

	// 首跑 -update 生成；复跑比对通过——"两次生成零 diff"的自证。
	problems, err := CheckMigrationV1Frozen(ms, golden, true)
	require.NoError(t, err)
	require.Empty(t, problems)
	problems, err = CheckMigrationV1Frozen(ms, golden, false)
	require.NoError(t, err)
	require.Empty(t, problems)

	// 人为违规：语句文本漂移必红（换行/空白/同义改写都算）。
	drifted := []engine.Migration{{Version: 1, Up: []string{"CREATE TABLE a (x)", "CREATE INDEX i ON a(x)"}}}
	problems, err = CheckMigrationV1Frozen(drifted, golden, false)
	require.NoError(t, err)
	require.NotEmpty(t, problems, "v1 文本漂移必红")

	// 结构性违规：清单不从 v1 起步必红。
	problems, err = CheckMigrationV1Frozen([]engine.Migration{{Version: 2}}, golden, false)
	require.NoError(t, err)
	require.NotEmpty(t, problems)
}

func TestCheckMigrationV1Frozen_MissingGoldenIsError(t *testing.T) {
	_, err := CheckMigrationV1Frozen(
		[]engine.Migration{{Version: 1, Up: []string{"x"}}},
		filepath.Join(t.TempDir(), "absent.golden"), false)
	require.Error(t, err, "golden 缺失是流程错误（生成步骤被跳过），不是清单问题")
}
